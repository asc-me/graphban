"""GRPH-1952 / P92 D4: `gban rules import --prose` opens a run for the customer's agent."""
from __future__ import annotations

import subprocess

import pytest
from gban import cli as cli_mod
from gban import config, rules
from gban.cli import main
from gban.client import EXIT_REFUSED


def _repo(tmp_path, files):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    for path, text in files.items():
        f = tmp_path / path
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
    subprocess.run(["git", "-C", str(tmp_path), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(tmp_path), "-c", "user.email=t@t", "-c", "user.name=t",
                    "commit", "-qm", "x"], check=True)
    return tmp_path


@pytest.fixture()
def home(tmp_path, monkeypatch):
    monkeypatch.setenv(config.HOME_ENV, str(tmp_path / "home"))
    for var in (config.URL_ENV, config.PROJECT_ENV, config.API_KEY_ENV, "GBFLEET_API_KEY"):
        monkeypatch.delenv(var, raising=False)
    config.save_settings(url="http://gb.invalid", project="core")
    config.save_session("refresh-token", user="alex@example.com")


class Rec:
    def __init__(self):
        self.calls = []

    def call(self, method, path, body=None):
        self.calls.append((method, path, body))
        return {"id": 7, "commit": body["commit"], "sources_unread": body["sources_unread"],
                "clean": not body["sources_unread"]}


FILES = {"CONTRIBUTING.md": "run tests", "AGENTS.md": "a", "docs/adr/0001-db.md": "pg",
         "docs/architecture.md": "arch", "src/app.py": "x", "docs/guide.md": "not prose",
         ".github/copilot-instructions.md": "c"}


def test_prose_sources_are_listed_unread_for_the_agent(tmp_path):
    repo = _repo(tmp_path / "r", FILES)
    body = rules.run_body(repo)
    assert len(body["commit"]) == 40
    assert [s["path"] for s in body["sources_unread"]] == [
        ".github/copilot-instructions.md", "AGENTS.md", "CONTRIBUTING.md",
        "docs/adr/0001-db.md", "docs/architecture.md"]
    assert all(s["reader"] == "agent" for s in body["sources_unread"])
    assert "sources_read" not in body


def test_an_unreadable_repo_is_refused_never_an_empty_run(tmp_path, home, monkeypatch, capsys):
    """Sabotage: let `prose_sources` return [] when git fails, and this fails."""
    not_a_repo = tmp_path / "plain"
    not_a_repo.mkdir()
    with pytest.raises(rules.Unreadable):
        rules.prose_sources(not_a_repo, "HEAD")
    rec = Rec()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    code = main(["rules", "import", "--prose", "--repo", str(not_a_repo)])
    assert code == EXIT_REFUSED and rec.calls == []
    assert "no import run was opened" in capsys.readouterr().err


def test_prose_opens_one_run_and_prints_the_skill_invocation(tmp_path, home, monkeypatch, capsys):
    repo = _repo(tmp_path / "r", FILES)
    rec = Rec()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--prose", "--repo", str(repo)]) == 0
    assert len(rec.calls) == 1
    method, path, _body = rec.calls[0]
    assert (method, path) == ("POST", "/api/projects/core/rules/import-runs")
    out = capsys.readouterr().out
    assert "/graphban-rules-import import_run=7 commit=" in out
    assert "unread  CONTRIBUTING.md" in out and "`propose_rule`" in out


STRUCTURED = {".github/workflows/db.yml": "on: [pull_request]\njobs: {}\n",
              ".github/workflows/nested/x.yml": "no", "CODEOWNERS": "billing/ @t\n",
              ".gitattributes": "gen/** linguist-generated\n", "web/uv.lock": "big lock",
              "src/api_pb2.py": "# Generated by protoc. DO NOT EDIT!\nx = 1\n",
              "src/app.py": "x = 1\n", "CONTRIBUTING.md": "Self-merge is fine.\n"}


def test_structured_import_ships_the_parsers_sources_and_lists_prose_unread(tmp_path):
    """`gban rules import` (no --prose) sends structured sources for the server's parsers."""
    repo = _repo(tmp_path / "r", STRUCTURED)
    body = rules.import_body(repo)
    assert sorted(body["files"]) == [".gitattributes", ".github/workflows/db.yml", "CODEOWNERS",
                                     "src/api_pb2.py", "web/uv.lock"]
    assert body["files"]["CODEOWNERS"] == "billing/ @t\n"
    assert body["files"]["web/uv.lock"] == ""  # generated by name; its text is not sent
    assert "DO NOT EDIT" in body["files"]["src/api_pb2.py"]
    assert body["branch"] == "main" and len(body["commit"]) == 40
    assert body["sources_unread"] == [{"path": "CONTRIBUTING.md", "reader": "agent"}]


def test_structured_import_posts_one_run_and_prints_three_buckets(tmp_path, home, monkeypatch,
                                                                  capsys):
    repo = _repo(tmp_path / "r", STRUCTURED)

    class Run(Rec):
        def call(self, method, path, body=None):
            self.calls.append((method, path, body))
            return {"id": 9, "commit": body["commit"], "clean": False,
                    "sources_unread": body["sources_unread"], "findings": [
                        {"bucket": "external", "stage": "Review", "label": "required reviews",
                         "quote": "`main` requires 2 approving review(s)"},
                        {"bucket": "proposed", "stage": "Plan", "quote": "billing owned by @t",
                         "proposal": {"rule_id": "custom.codeowners-t"}},
                        {"bucket": "gap", "stage": "Review", "label": "review ownership",
                         "quote": "1 CODEOWNERS entries"}]}
    rec = Run()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--repo", str(repo)]) == 0
    (method, path, body), = rec.calls
    assert (method, path) == ("POST", "/api/projects/core/rules/import-runs/scan")
    assert "CODEOWNERS" in body["files"]
    out = capsys.readouterr().out
    assert "proposed" in out and "EXTERNAL" in out and "guidance + gap" in out
    assert out.index("proposed") < out.index("EXTERNAL") < out.index("guidance + gap")
    assert "/graphban-rules-import import_run=9" in out


def test_structured_import_of_an_unreadable_repo_opens_nothing(tmp_path, home, monkeypatch,
                                                               capsys):
    plain = tmp_path / "plain"
    plain.mkdir()
    rec = Rec()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--repo", str(plain)]) == EXIT_REFUSED and rec.calls == []
    assert "no import run was opened" in capsys.readouterr().err


# ---- the rescan and its drift (GRPH-1953 / P92 D5) ----------------------------------------

class ScanRec(Rec):
    def __init__(self, clean=True):
        super().__init__()
        self.clean = clean

    def call(self, method, path, body=None):
        self.calls.append((method, path, body))
        return {"id": 9, "commit": body["commit"], "clean": self.clean,
                "sources_unread": [{"path": "CONTRIBUTING.md", "reader": "agent"}] + (
                    [] if self.clean else [{"path": "branch protection: main",
                                            "reason": "token lacks admin:read"}]),
                "findings": [{"bucket": "notice", "label": "source gone",
                              "text": "build.engine_evidence was adopted from ci.yml",
                              "source": {"path": ".github/workflows/ci.yml"}}]}


def test_a_rescan_prints_its_drift_notices_and_adopts_nothing(tmp_path, home, monkeypatch, capsys):
    repo = _repo(tmp_path / "r", STRUCTURED)
    rec = ScanRec()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--repo", str(repo)]) == 0
    (method, path, body), = rec.calls
    assert (method, path) == ("POST", "/api/projects/core/rules/import-runs/scan")
    assert "CODEOWNERS" in body["files"]
    out = capsys.readouterr().out
    assert "notice" in out and "source gone" in out and "nothing is adopted here" in out


def test_an_unread_source_fails_the_step(tmp_path, home, monkeypatch, capsys):
    """CI reports an unread source as a failed step, never as a pass."""
    repo = _repo(tmp_path / "r", STRUCTURED)
    rec = ScanRec(clean=False)
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--repo", str(repo), "--branch", "trunk"]) == EXIT_REFUSED
    assert rec.calls[0][2]["branch"] == "trunk"
    out = capsys.readouterr().out
    assert "unread  branch protection: main" in out and "NOT CLEAN" in out


def test_ci_template_prints_the_workflow_and_calls_nothing(tmp_path, home, monkeypatch, capsys):
    rec = ScanRec()
    monkeypatch.setattr(cli_mod, "authenticated", lambda url, act="": rec)
    assert main(["rules", "import", "--ci-template", "--branch", "trunk"]) == 0
    assert rec.calls == []
    out = capsys.readouterr().out
    assert "  push:\n    branches: [trunk]\n    paths:\n" in out
    for p in (".github/workflows/**", "**/CODEOWNERS", "**/.gitattributes"):
        assert f'      - "{p}"' in out
    assert "gban rules import --branch trunk" in out
    assert "permissions:\n  contents: read\n" in out
    # It files; it never adopts, and its step is not made to pass on an unread source.
    body = out.split("jobs:", 1)[1]
    assert "adopt" not in body and "|| true" not in out and "continue-on-error" not in out


