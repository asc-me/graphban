"""Claude Code transcripts: append-only JSONL (GRPH-304 / PRD-16).

Shipped first because append-only JSONL is the simplest watermark shape there is — a line
count. Nothing rewrites earlier lines, so "resume after N" is exact rather than a guess,
and getting the incremental contract right on the easy case is what makes the hard ones
(a database cursor, a rotating log) implementable against the same interface.
"""
from __future__ import annotations

import json
import logging
import os
import re
from pathlib import Path

from app.services.ingest import Event

logger = logging.getLogger(__name__)

# Claude Code delivers several things as user-role records that no user typed: subagent
# results, system reminders, hook output, slash-command expansions. They are long, so a
# length bar waves them straight through — 40 of the 80 long "user" messages in the real
# corpus were these, not a person (GRPH-345).
#
# Matched by their opening tag rather than by content, because the tag is the harness
# speaking in its own voice and is the only part guaranteed to be there.
_INJECTED = re.compile(
    r"^\s*<(task-notification|system-reminder|local-command-[a-z]+|command-(name|message|args)"
    r"|user-prompt-submit-hook|hook-\w+|ide_\w+|bash-(stdout|stderr|input))\b", re.I)

# The same thing without a tag to give it away. These are the biggest single source of junk
# prose in the real corpus: 19 of 42 surviving messages were CONTEXT-COMPACTION SUMMARIES —
# 11k–19k characters each, written by the assistant about the session and replayed in the
# user's slot. A skill body arrives the same way; one measured 804,441 characters.
#
# Recognised by their opening line because that line is fixed boilerplate, while everything
# after it is the session's own content and would match anything.
_INJECTED_PREFIXES = (
    "this session is being continued from a previous conversation",
    "base directory for this skill:",
    "caveat: the messages below were generated by the user while running",
    "claude in chrome setup completed",
)
HARNESS_KIND = "harness"
# Claude Code delivers tool results as user-role records too. They are evidence when they
# FAILED, and never on the strength of having been said by "the user".
TOOL_RESULT_KIND = "tool_result"

# Where Claude Code keeps session transcripts. Overridable so a test never depends on the
# developer's home directory, and so an operator can point at an archive.
_ROOT_ENV = "GRAPHBAN_CLAUDE_TRANSCRIPTS"
_DEFAULT_ROOT = "~/.claude/projects"


class ClaudeCodeAdapter:
    name = "claude-code"

    def __init__(self, root: str | None = None):
        self.root = Path(os.path.expanduser(root or os.getenv(_ROOT_ENV) or _DEFAULT_ROOT))

    def discover(self) -> list[str]:
        """Every `.jsonl` under the root, sorted for a stable run order.

        No try/except here, deliberately. `rglob` already yields nothing for a root that is
        missing, unreadable, or not a directory — verified, not assumed: an `except OSError`
        sat here first and sabotage showed it could never fire, because pathlib swallows all
        three. An unreachable handler is worse than none, since it implies a guarantee that
        something else is actually providing.

        The resilience that IS load-bearing lives in `parse`, where `open()` genuinely
        raises on a locked file mid-run.
        """
        return sorted(str(p) for p in self.root.rglob("*.jsonl") if p.is_file())

    def parse(self, source: str, watermark: str | None) -> tuple[list[Event], str | None]:
        """Events after line `watermark`, and the new line count.

        The watermark is a LINE COUNT rather than a byte offset. Both work for append-only
        data, but a line count survives a file being rewritten with different line endings,
        and it is readable in the database when someone is working out why a run skipped
        something.
        """
        start = int(watermark or 0)
        rows: list[tuple[int, dict]] = []
        seen = 0
        try:
            with open(source, encoding="utf-8", errors="replace") as fh:
                for seen, line in enumerate(fh, start=1):
                    row = self._row(source, line)
                    if row is not None:
                        rows.append((seen, row))
        except OSError as e:
            # Locked, deleted mid-run, or permission-denied. The run continues with the
            # watermark unmoved, so nothing is lost and the next run picks it up.
            logger.warning("ingest skipped %s: %s", source, e)
            return [], watermark

        # The WHOLE file is read even on an incremental run, because a result after the
        # watermark routinely refers to a call before it — the id map has to span the join
        # or every resumed run loses the tool name for its first few results.
        events = _episodes(source, rows, start, self.name)
        for line_no, row in rows:
            if line_no > start:
                ev = self._event(source, row)
                if ev is not None:
                    events.append(ev)
        return events, str(max(seen, start))

    def _row(self, source: str, line: str) -> dict | None:
        """One JSONL line to a dict, or None.

        A malformed record is a WARN and a skip, never an exception — a single truncated
        line at the end of a live transcript is the NORMAL state of a session in progress,
        not a corruption worth failing a run over.
        """
        line = line.strip()
        if not line:
            return None
        try:
            row = json.loads(line)
        except (ValueError, TypeError):
            logger.warning("ingest skipped a malformed record in %s", source)
            return None
        if not isinstance(row, dict):
            logger.warning("ingest skipped a non-object record in %s", source)
            return None
        return row

    def _event(self, source: str, row: dict) -> Event | None:
        """One record to an Event, or None if it carries nothing to learn from."""
        text = _text_of(row.get("message") or row)
        tool = _tool_of(row)
        result = row.get("toolUseResult")
        # A tool RESULT is its own record, separate from the call that produced it — 910
        # results against 18,173 calls in the real corpus. Requiring text or a tool name
        # dropped every one of them, and with them the entire failure signal (GRPH-342).
        if isinstance(result, dict) and not text:
            text = _result_text(result)
        # **A FAILED tool call carries no `toolUseResult` at all** — there was no structured
        # output to record, so the error text is a plain string on the `tool_result` block.
        # All 154 real errors in the corpus have this shape, and every one was being dropped
        # by the guard below: no text, no tool name, no result dict. GRPH-342 believed it had
        # recovered the failure signal while the actual failures stayed invisible, and what
        # it recorded instead was benign stderr from commands that had SUCCEEDED (GRPH-345).
        if not text:
            text = _tool_result_text(row)
        if not text and not tool and not isinstance(result, dict):
            return None
        # A FAILED result belongs to its episode, which carries the same error text plus
        # what was done differently next. Emitting it here too would file the symptom
        # alongside the lesson and let the pair corroborate itself (GRPH-349).
        if _is_error_of(row) is True:
            return None

        # A record the harness wrote in the user's slot is not the user talking. Relabelled
        # here rather than filtered, so it stays visible to anything that wants it and only
        # loses the standing that "a person said this" confers (GRPH-345).
        #
        # Tool results are the larger case and the less obvious one: Claude Code delivers
        # every one of them as a USER-role record. Left alone they inherit the standing of a
        # human turn, so any result the harness did not flag sails through as prose — which
        # is how "Async agent launched successfully" became a lesson 600 times over.
        kind = str(row.get("type") or "unknown")
        if kind == "user":
            if isinstance(result, dict) or _has_tool_result(row):
                kind = TOOL_RESULT_KIND
            elif _is_injected(row, text):
                kind = HARNESS_KIND

        return Event(
            session_id=str(row.get("sessionId") or Path(source).stem),
            harness=self.name,
            project=str(row.get("cwd") or ""),
            ts=str(row.get("timestamp") or ""),
            # A plain string, so a harness with a kind we have never seen costs no change
            # here (PRD-16).
            kind=kind,
            text=text,
            tool_name=tool,
            exit_code=_exit_of(row),
            metadata={"source": source, "outcome": _outcome_of(row)},
        )


def _text_of(message) -> str:
    """The human-readable text of a record, whatever shape it arrived in."""
    if isinstance(message, str):
        return message
    if not isinstance(message, dict):
        return ""
    content = message.get("content")
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = [c.get("text", "") for c in content
                 if isinstance(c, dict) and c.get("type") == "text"]
        return "\n".join(p for p in parts if p)
    return ""


def _result_text(result: dict) -> str:
    """What a tool result contributes to a lesson.

    `stderr` first and deliberately: a command that FAILED is the higher-value signal, and
    burying it under kilobytes of successful stdout is how it gets lost. Both are capped —
    a full build log is not a lesson, and the promotion ladder scores text it can compare.
    """
    err = str(result.get("stderr") or "").strip()
    if err:
        return f"stderr: {err[:600]}"
    out = str(result.get("stdout") or "").strip()
    return f"stdout: {out[:600]}" if out else ""


# --- episodes (GRPH-349) -----------------------------------------------------------------
# A failure on its own is a SYMPTOM, not a lesson. Measured: feeding the classifier bare
# failures produced confidently wrong rules — `cd:1: no such file or directory: backend`
# (x10) became "Ensure 'backend' directory exists before running commands", drafted as a
# shell guard. The directory exists. The shell does not persist a working directory between
# calls, so a relative path resolves from somewhere else — and nothing in the failure text
# says so. The model had to guess, and guessed plausibly.
#
# What disambiguates it is what was done DIFFERENTLY next. That difference is the lesson,
# and it is the one thing no model can reconstruct from the failure alone.
EPISODE_LOOKAHEAD = 40      # results, not lines — how far a fix may be from its failure
# CONTAINMENT, not Jaccard: a fix usually adds detail rather than replacing it, so
# `cd backend && pytest` -> `cd /abs/path/backend && pytest` should still read as the same
# attempt even though the longer form drags the union up and Jaccard down.
_RESOLVE_MIN_OVERLAP = 0.6
# Below this many tokens, containment cannot tell a fix from a different call: `AL-41 done`
# and `AL-40 done` share two words of three and score 0.67, which paired one item's failure
# with another item's success and invented a resolution. Short calls must match exactly —
# which makes them `transient` by definition, never `resolved`.
_MIN_TOKENS_FOR_PARTIAL = 4

UNRESOLVED_PREFIX = "UNRESOLVED — no successful retry followed."
TRANSIENT_PREFIX = "TRANSIENT — the identical call succeeded on retry, nothing was changed."


def _call_index(rows: list[tuple[int, dict]]) -> dict[str, tuple[str, dict]]:
    """`tool_use_id` -> (tool name, input). Verified complete on a real transcript: all
    1,295 results resolved to their call."""
    calls: dict[str, tuple[str, dict]] = {}
    for _, row in rows:
        for b in _blocks(row):
            if isinstance(b, dict) and b.get("type") == "tool_use" and b.get("id"):
                calls[str(b["id"])] = (str(b.get("name") or ""), b.get("input") or {})
    return calls


# What a call was aiming AT, in preference order, versus prose written about it. Comparing
# whole inputs measured writing style instead of target: two `update_item` calls carrying
# long "done, PR merged, deployed, verified" notes overlap heavily on boilerplate, which
# paired AL-57's failure with AL-40's success. And a Bash `description` differing ("Show
# final CI results" vs "Show CI results after rerun") made an identical rerun look like a
# fix.
_IDENTITY_KEYS = ("command", "file_path", "path", "notebook_path", "url", "pattern",
                  "query", "id", "item_id", "name")
_PROSE_KEYS = ("description", "explanation", "reason", "comment", "body", "evidence",
               "notes", "text", "content", "message")


def _call_text(inp) -> str:
    """What the call was aiming at, flattened.

    Identity arguments when the call has any — they say WHICH thing was acted on, which is
    what "the same attempt again" has to mean. Otherwise every scalar except the prose
    fields, so a tool nobody anticipated still compares on something.
    """
    if not isinstance(inp, dict):
        return str(inp or "")
    identity = [str(inp[k]) for k in _IDENTITY_KEYS
                if isinstance(inp.get(k), (str, int, float))]
    if identity:
        return " ".join(identity)
    return " ".join(str(v) for k, v in inp.items()
                    if isinstance(v, (str, int, float)) and k not in _PROSE_KEYS)


def _overlap(a: str, b: str) -> float:
    """Token containment: how much of the SMALLER call the two share.

    Deliberately crude and dependency-free — it only has to tell "the same command again,
    adjusted" from "some unrelated command". Containment rather than Jaccard because a fix
    typically ADDS detail, and Jaccard punishes the longer corrected form for being longer.
    """
    ta = {t for t in re.split(r"\W+", a.lower()) if t}
    tb = {t for t in re.split(r"\W+", b.lower()) if t}
    if not ta or not tb:
        return 0.0
    score = len(ta & tb) / min(len(ta), len(tb))
    # Too few tokens for a partial match to mean anything — demand an exact one.
    if min(len(ta), len(tb)) < _MIN_TOKENS_FOR_PARTIAL and score < 1.0:
        return 0.0
    return score


def _same_call(a: str, b: str) -> bool:
    """Was the retry the SAME call, character for character (bar whitespace)?"""
    return " ".join(a.lower().split()) == " ".join(b.lower().split())


def _episode_text(tool: str, failed: str, error: str, fixed: str | None) -> str:
    """The pair, written so the DIFFERENCE is the visible part.

    The resolution goes last and is labelled, because that is the half the classifier has
    never had and the half a reader needs in order to state the rule.

    Three shapes, and keeping them apart is the point:

    - **resolved** — something was done differently and it worked. The only shape that is
      a lesson, and the only one classification ever sees.
    - **unresolved** — nothing fixed it. Evidence that something is repeatedly painful.
    - **transient** — the identical call succeeded on retry. Nothing was learned, because
      nothing was changed; it says the tool is flaky, which is a different claim.

    Filing all three as "a failure that was followed by a success" would make the last two
    read as the first — which is how a retry loop becomes a rule about what to do.
    """
    body = [f"Tool: {tool}", f"Attempted: {failed[:400]}", f"Failed: {error[:600]}"]
    if fixed is None:
        return UNRESOLVED_PREFIX + "\n" + "\n".join(body)
    if _same_call(failed, fixed):
        return TRANSIENT_PREFIX + "\n" + "\n".join(body)
    return "\n".join(body + [f"Resolved by: {fixed[:400]}"])


def _episodes(source: str, rows: list[tuple[int, dict]], start: int,
              harness: str) -> list[Event]:
    """Failure/resolution pairs for every failed call after `start`.

    A failure is paired with the next SUCCESSFUL result from the same tool whose arguments
    still overlap it — "the same thing, attempted differently". Unpaired failures are still
    emitted, marked `UNRESOLVED`, because a failure nobody fixed is evidence of friction
    even though it is not a lesson; the marker is what keeps the two from reading alike.

    **Known boundary limitation.** On an incremental run a failure near the tail may have
    its fix in lines not yet written, so it is recorded unresolved and the later fix is
    missed. Deliberate: the alternative is holding the watermark back, which re-emits events
    and manufactures duplicate corroboration. Missing a lesson is the safe direction;
    inventing one is not.
    """
    calls = _call_index(rows)
    results: list[tuple[int, dict, str, bool]] = []
    for line_no, row in rows:
        for b in _blocks(row):
            if isinstance(b, dict) and b.get("type") == "tool_result":
                tuid = str(b.get("tool_use_id") or "")
                results.append((line_no, row, tuid, b.get("is_error") is True))
                break

    events: list[Event] = []
    for i, (line_no, row, tuid, failed) in enumerate(results):
        if not failed or line_no <= start:
            continue
        tool, inp = calls.get(tuid, ("", {}))
        attempted = _call_text(inp)
        error = _tool_result_text(row)
        if not error:
            continue

        # BEST match in the window, not the first. Real data: `update_item AL-41` was paired
        # with `update_item AL-40` because they share the word "done" and it came first,
        # inventing a resolution from a different item entirely. Scoring the whole window
        # lets the actual retry win when one exists.
        fix, best = None, 0.0
        for _, _later_row, later_id, later_failed in results[i + 1:i + 1 + EPISODE_LOOKAHEAD]:
            if later_failed:
                continue
            later_tool, later_inp = calls.get(later_id, ("", {}))
            if not later_tool or later_tool != tool:
                continue
            later_text = _call_text(later_inp)
            score = _overlap(attempted, later_text)
            if score >= _RESOLVE_MIN_OVERLAP and score > best:
                fix, best = later_text, score
                if score >= 1.0:  # nothing can beat it; stop paying for the rest
                    break

        text = _episode_text(tool, attempted, error, fix)
        # Only a genuine CHANGE is a lesson. An identical retry that worked says the tool is
        # flaky, which is worth recording and is not a rule.
        resolved = fix is not None and not _same_call(attempted, fix)
        events.append(Event(
            session_id=str(row.get("sessionId") or Path(source).stem),
            harness=harness,
            project=str(row.get("cwd") or ""),
            ts=str(row.get("timestamp") or ""),
            kind="episode",
            text=text,
            tool_name=tool,
            metadata={"source": source, "outcome": "failed", "resolved": resolved,
                      "episode": ("resolved" if resolved
                                  else "transient" if fix is not None else "unresolved")},
        ))
    return events


def _blocks(row: dict) -> list:
    """The content blocks of a record, or an empty list. Four callers need this shape and
    each guard was written out longhand until they disagreed about what counted."""
    msg = row.get("message")
    blocks = msg.get("content") if isinstance(msg, dict) else None
    return blocks if isinstance(blocks, list) else []


# What the harness records about a message it wrote itself (GRPH-347). A POSITIVE signal,
# which is what makes it worth having: the text heuristics below are a denylist, so every new
# skill or slash command is a new opening line nobody has added yet, and the gap only shows
# up as junk in the corpus weeks later.
#
#   isMeta                     — injected content (skill bodies, system-prompt sections)
#   isCompactSummary           — a context-compaction summary, written ABOUT the session
#   isVisibleInTranscriptOnly  — shown to the reader, never part of the conversation
#   promptSource == "system"   — the turn was generated, not typed
#
# A genuine turn carries `userType: "external"` and none of these.
_HARNESS_FLAGS = ("isMeta", "isCompactSummary", "isVisibleInTranscriptOnly")


def _is_injected(row: dict, text: str) -> bool:
    """Did the harness write this into the user's slot, rather than a person typing it?

    Structural flags first, because they are the harness stating what it did rather than us
    inferring it from wording. The text patterns stay as a FALLBACK — a transcript written
    by an older Claude Code carries none of these fields, and treating their absence as
    "a person typed this" would be the same mistake as reading an absence as a clean result.
    """
    if any(row.get(f) is True for f in _HARNESS_FLAGS):
        return True
    if str(row.get("promptSource") or "") == "system":
        return True
    if _INJECTED.match(text):
        return True
    head = text.lstrip()[:80].lower()
    return any(head.startswith(p) for p in _INJECTED_PREFIXES)


def _has_tool_result(row: dict) -> bool:
    """Is this record a tool RESULT, whatever role it arrived under?"""
    return any(isinstance(b, dict) and b.get("type") == "tool_result"
               for b in _blocks(row))


def _tool_result_text(row: dict) -> str:
    """The text a `tool_result` block carries directly.

    The shape a FAILED call arrives in, and the only place its error text exists. Capped
    like every other body: a lesson is the error, not the log that followed it.
    """
    for b in _blocks(row):
        if not isinstance(b, dict) or b.get("type") != "tool_result":
            continue
        content = b.get("content")
        if isinstance(content, str):
            return content.strip()[:600]
        if isinstance(content, list):
            parts = [c.get("text", "") for c in content
                     if isinstance(c, dict) and c.get("type") == "text"]
            joined = "\n".join(p for p in parts if p).strip()
            if joined:
                return joined[:600]
    return ""


def _tool_of(row: dict) -> str:
    for b in _blocks(row):
        if isinstance(b, dict) and b.get("type") == "tool_use" and b.get("name"):
            return str(b["name"])
    return ""


def _exit_of(row: dict) -> int | None:
    """A numeric exit code, when the harness records one.

    Claude Code does NOT — verified against 74 real transcripts: 18,167 tool calls and
    zero numeric codes. The field stays because the `Event` shape is shared and other
    harnesses do emit one; read `metadata["outcome"]` for the signal that is actually
    available here.
    """
    result = row.get("toolUseResult")
    if isinstance(result, dict):
        for key in ("exitCode", "exit_code", "returncode"):
            if isinstance(result.get(key), int):
                return result[key]
    return None


def _is_error_of(row: dict) -> bool | None:
    """The harness's OWN verdict on a tool call, or None if it did not record one.

    `is_error` sits on the `tool_result` block inside the message, not on the sibling
    `toolUseResult` payload — which is why the first pass missed it.
    """
    for b in _blocks(row):
        if isinstance(b, dict) and b.get("type") == "tool_result":
            flag = b.get("is_error")
            if isinstance(flag, bool):
                return flag
    return None


def _outcome_of(row: dict) -> str:
    """`ok` | `failed` | `unknown` — did this tool call work (GRPH-342, corrected GRPH-345).

    PRD-16 makes the failure signal first-class because "a lesson about a command that
    FAILED is worth more than one about a command that ran". `exit_code` cannot carry it
    for this harness, and leaving it at None meant every one of 18,167 real tool calls read
    as untroubled — `None` conflating "succeeded" with "not recorded".

    **GRPH-342 then inferred the answer from `stderr` and `returnCodeInterpretation`, on the
    assumption that Claude Code recorded nothing better. It does.** `is_error` is the
    harness's own verdict, and the inference disagreed with it badly: of 118 events the old
    rule called failures, 90 were `Shell cwd was reset to …` — a routine notice on stderr —
    and 28 were `No matches found`, which is what a search does when it finds nothing. A
    corpus of "failures" that is three-quarters benign notices trains the ladder on noise.

    Read the recorded flag; infer only where there is none. `interrupted` survives as a
    fallback because it is a fact rather than a guess, and `unknown` still means the record
    carries no result at all — never a claim that anything went well.
    """
    flag = _is_error_of(row)
    if flag is not None:
        return "failed" if flag else "ok"
    result = row.get("toolUseResult")
    if not isinstance(result, dict):
        return "unknown"
    if result.get("interrupted") is True:
        return "failed"
    # A recorded exit code is a FACT, not an inference — the one piece of the old fallback
    # worth keeping. Claude Code never writes one, but the `Event` shape is shared and a
    # harness that does emit one should not have it read as "nothing was recorded".
    code = _exit_of(row)
    if code is not None:
        return "ok" if code == 0 else "failed"
    if "stdout" in result or "filePath" in result or "type" in result:
        return "ok"
    return "unknown"
